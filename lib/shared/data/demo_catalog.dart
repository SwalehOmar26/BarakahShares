    for (final business in businesses) {
      if (business.id == id) return business;
    }
    return null;
  }

  static ProfitSnapshot? profitFor(String businessId) {
    for (final snapshot in profits) {
      if (snapshot.businessId == businessId) return snapshot;
    }
    return null;
  }

